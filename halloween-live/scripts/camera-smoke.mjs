import {chromium} from '@playwright/test';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
const outputDir=resolve(process.env.LIVE_QA_OUTPUT_DIR||'../work/halloween-qa');await mkdir(outputDir,{recursive:true});
import QRCode from '../../node_modules/qrcode/lib/index.js';
import {spawnSync} from 'node:child_process';
await QRCode.toFile(`${outputDir}/camera-qr.png`,'PIVNIK:DEMO_token_00000003',{width:350,margin:4});
const video=spawnSync('ffmpeg',['-y','-loop','1','-i',`${outputDir}/camera-qr.png`,'-vf','scale=350:350,pad=640:480:(ow-iw)/2:(oh-ih)/2:white','-t','3','-r','15','-pix_fmt','yuv420p',`${outputDir}/camera-qr.y4m`]);
if(video.status)throw Error('ffmpeg');
const codes=Object.fromEntries((await readFile('.data/demo-access.txt','utf8')).split('\n').map(l=>l.split(': ')));
const b=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream',`--use-file-for-fake-video-capture=${outputDir}/camera-qr.y4m`]});
const c=await b.newContext({permissions:['camera'],viewport:{width:440,height:956},isMobile:true,hasTouch:true});
const p=await c.newPage();const errors=[];p.on('pageerror',e=>errors.push(e.message));await p.goto('http://localhost:4317/scanner');
await p.locator('[name=account]').fill('scanner');await p.locator('[name=password]').fill(codes.scanner);await p.locator('#login-form button').click();
await p.getByText('Гость зарегистрирован',{exact:true}).waitFor({timeout:15000});
await p.screenshot({path:`${outputDir}/scanner-qr-success.png`,fullPage:true});
await p.getByText('Уже зарегистрирован',{exact:true}).waitFor({timeout:10000});
const result=await p.request.get('http://localhost:4317/api/state?view=scanner');const s=await result.json();
if(s.guests.filter(g=>g.userId==='3').length!==1)throw Error('Duplicate registration');
await writeFile(`${outputDir}/camera-result.json`,JSON.stringify({decodedExistingFormat:true,automaticStart:true,duplicateBlocked:true,errors},null,2));
await b.close();
