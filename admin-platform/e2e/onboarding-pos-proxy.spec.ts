import {expect,test} from '@playwright/test'

test('manager configures native proxy: no event, incomplete sync, then confirmed empty report; resume keeps masked key and pending deployment',async({page,request,context})=>{
 await context.grantPermissions(['clipboard-read','clipboard-write'])
 await page.goto('/')
 await expect(page).toHaveTitle('SPACEVERSE — Панель владельца')
 await page.getByLabel('Email',{exact:true}).fill('owner@fixture.invalid')
 await page.getByLabel('Пароль',{exact:true}).fill('Synthetic-Onboarding-Only-2026!')
 await page.getByRole('button',{name:'Войти',exact:true}).click()
 for(const label of ['Колесо','Достижения','Рассылки'])await expect(page.getByRole('navigation').getByRole('button',{name:label,exact:true})).toHaveCount(0)
 const wizard=page.getByRole('region',{name:'Подключение заведений'})
 await expect(wizard).toBeVisible()
 await expect(wizard.getByText('Загружаем черновики…',{exact:true})).toHaveCount(0)
 if(await wizard.getByRole('button',{name:'Закрыть',exact:true}).isVisible())await wizard.getByRole('button',{name:'Закрыть',exact:true}).click()
 await wizard.getByRole('button',{name:'Добавить заведение'}).click()
 await wizard.getByLabel('Организация',{exact:true}).selectOption('10')
 await wizard.getByLabel('Название заведения',{exact:true}).fill('Прокси '+test.info().project.name)
 const draftResponse=page.waitForResponse(response=>response.request().method()==='POST'&&response.url().endsWith('/api/admin/onboarding/drafts'))
 await wizard.getByRole('button',{name:'Сохранить черновик',exact:true}).click()
 const draft=await (await draftResponse).json()
 await wizard.getByRole('button',{name:'Сохранить приложение',exact:true}).click()
 const scopeResponse=page.waitForResponse(response=>response.request().method()==='PUT'&&response.url().endsWith('/scope'))
 await wizard.getByRole('button',{name:'Подготовить область',exact:true}).click()
 const scope=await (await scopeResponse).json()
 const progress=wizard.getByRole('region',{name:'Шаги подключения'}),proxy=wizard.getByRole('region',{name:'Связь с кассой через прокси'})
 const terminalId='terminal-'+test.info().project.name
 await progress.getByLabel('ID терминала',{exact:true}).fill(terminalId)
 await progress.getByRole('button',{name:'Сохранить прогресс',exact:true}).click()
 await expect(progress.getByRole('status')).toContainText('сохранены')
 const fixture=await request.post('/__fixture/pos/create',{data:{manifest:scope.runtimeManifest,terminalId,storeId:'store-'+test.info().project.name}})
 expect(fixture.status()).toBe(200);const device=await fixture.json()
 await proxy.getByLabel('Магазин прокси',{exact:true}).fill(device.storeId)
 await proxy.getByLabel('Ключ устройства прокси',{exact:true}).fill(device.deviceKey)
 await proxy.getByRole('button',{name:'Сохранить ключ устройства',exact:true}).click()
 await expect(proxy.getByRole('status')).toContainText('Связь ещё не проверена')
 await expect(proxy.getByLabel('Ключ устройства прокси',{exact:true})).toHaveValue('')
 await proxy.getByRole('button',{name:'Проверить связь',exact:true}).click()
 await expect(proxy.getByText('С кассы ещё не пришло тестовое событие.',{exact:false})).toBeVisible()
 await expect(proxy.getByText('Отчёт недоступен · сумма неизвестна',{exact:true})).toBeVisible()
 expect((await request.post('/__fixture/pos/event',{data:{runtimeKey:scope.runtimeManifest.runtimeKey}})).status()).toBe(200)
 await proxy.getByRole('button',{name:'Проверить связь',exact:true}).click()
 await expect(proxy.getByText('Касса ответила, но полная загрузка документов',{exact:false})).toBeVisible()
 expect((await request.post('/__fixture/pos/sync',{data:{runtimeKey:scope.runtimeManifest.runtimeKey}})).status()).toBe(200)
 await proxy.getByRole('button',{name:'Проверить связь',exact:true}).click()
 await expect(proxy.getByText('Связь подтверждена',{exact:true})).toBeVisible()
 await expect(progress.getByText('0 ₽ · 0 чеков · данные получены за проверенный период.',{exact:true})).toBeVisible()
 await expect(progress.getByText('Заведение ещё не запущено',{exact:true})).toBeVisible()
 const venues=page.getByRole('region',{name:'Все заведения'})
 const row=venues.getByRole('listitem').filter({has:page.getByText('Прокси '+test.info().project.name,{exact:true})})
 await expect(row.getByText('0 ₽ · 0 чеков · данные получены',{exact:true})).toBeVisible()
 await expect(row.getByText('Ожидает подключения',{exact:true})).toBeVisible()
 await expect(row.getByText('Последнее событие устройства',{exact:true})).toBeVisible()
 await expect(row.getByText('Требует внимания:',{exact:false})).toBeVisible()
 await row.getByText('Нужна помощь разработчика?',{exact:true}).click()
 await row.getByLabel('Что не получается',{exact:true}).fill('Нужна помощь с запуском приложения')
 await expect(row.getByLabel('Текст обращения',{exact:true})).toHaveValue(/Нужна помощь с запуском приложения/)
 expect(await row.getByLabel('Текст обращения',{exact:true}).inputValue()).not.toContain(device.deviceKey)
 await row.getByRole('button',{name:'Скопировать обращение разработчику',exact:true}).click()
 await expect(row.getByRole('status')).toContainText('Обращение скопировано')
 expect(await page.evaluate(()=>navigator.clipboard.readText())).toContain('Нужна помощь с запуском приложения')
 await page.reload()
 await row.getByRole('button',{name:'Продолжить подключение',exact:true}).click()
 await expect(proxy.getByText('Связь подтверждена',{exact:true})).toBeVisible()
 await expect(proxy.getByLabel('Ключ устройства прокси',{exact:true})).toHaveValue('')
 const live=await page.request.get('/api/admin/onboarding/drafts/'+draft.id+'/progress')
 expect(live.status()).toBe(200);expect(await live.json()).toMatchObject({status:'pending',runtimeStatus:'not_provisioned',published:false,report:{state:'available',netCents:'0',receiptCount:0}})
 expect(await page.evaluate(()=>JSON.stringify({...localStorage,...sessionStorage}))).not.toContain(device.deviceKey)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
})
