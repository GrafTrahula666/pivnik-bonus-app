import { expect,test } from '@playwright/test'

test('owner invitation opens the real resumable manager wizard and revoke closes access',async({page,browser})=>{
  await page.goto('/')
  await page.getByLabel('Email',{exact:true}).fill('owner@fixture.invalid')
  await page.getByLabel('Пароль',{exact:true}).fill('Synthetic-Onboarding-Only-2026!')
  await page.getByRole('button',{name:'Войти',exact:true}).click()
  const invitations=page.getByRole('region',{name:'Приглашения'})
  await expect(invitations).toBeVisible()
  await invitations.getByLabel('Организация приглашения').selectOption({label:'Север'})
  await invitations.getByRole('button',{name:'Создать приглашение',exact:true}).click()
  const link=invitations.getByLabel('Ссылка приглашения')
  await expect(link).toHaveValue(/#invite=SVI-/)
  const url=await link.inputValue()
  // Open the retained link again after reload; no token/password in browser storage.
  await page.reload()
  await invitations.getByRole('button',{name:'Открыть ссылку',exact:true}).first().click()
  await expect(link).toHaveValue(url)
  const recipient=await browser.newContext({viewport:page.viewportSize()||undefined})
  const manager=await recipient.newPage()
  try{
    await manager.goto(url)
    await expect(manager.getByRole('heading',{name:'Подключение по приглашению'})).toBeVisible()
    await manager.getByLabel('Ваше имя').fill('Новый управляющий')
    await manager.getByLabel('Email',{exact:true}).fill(`manager-${test.info().project.name}-${Date.now()}@fixture.invalid`)
    await manager.getByLabel('Новый пароль').fill('Synthetic-Manager-Only-2026!')
    await manager.getByRole('button',{name:'Создать учётную запись и открыть мастер'}).click()
    const wizard=manager.getByRole('region',{name:'Подключение заведений'})
    await expect(wizard).toBeVisible()
    await wizard.getByRole('button',{name:'Добавить заведение'}).click()
    await expect(wizard.getByLabel('Организация',{exact:true})).toHaveValue('10')
    await expect(wizard.getByLabel('Организация',{exact:true}).locator('option')).not.toContainText(['Юг','Новая организация'])
    await wizard.getByLabel('Название заведения',{exact:true}).fill('Кафе управляющего '+test.info().project.name)
    const saved=manager.waitForResponse(response=>response.request().method()==='POST'&&response.url().endsWith('/api/admin/onboarding/drafts'))
    await wizard.getByRole('button',{name:'Сохранить черновик',exact:true}).click()
    const draft=await (await saved).json() as {id:string}
    await expect(wizard.getByText('Черновик сохранён. Заведение ещё не подключено.',{exact:true})).toBeVisible()
    await manager.reload()
    await expect(wizard.getByLabel('Название заведения',{exact:true})).toHaveValue('Кафе управляющего '+test.info().project.name)
    await wizard.getByRole('button',{name:'Сохранить приложение',exact:true}).click()
    await wizard.getByRole('button',{name:'Подготовить область',exact:true}).click()
    await expect(wizard.getByText('Подготовлено · выключено',{exact:true})).toBeVisible()
    await expect(wizard.getByText('Не запускалась',{exact:true})).toBeVisible()
    const live=await recipient.request.get('/api/admin/onboarding/drafts/'+draft.id+'/application')
    expect(live.status()).toBe(200)
    expect((await live.json()).application.contract).toMatchObject({runtimeStatus:'not_provisioned',published:false,legacyDataAccess:false})
    expect(await manager.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth)).toBeLessThanOrEqual(1)
    await page.reload()
    await invitations.getByRole('button',{name:'Отозвать',exact:true}).first().click()
    await expect(invitations.getByText('Управляющий · Отозвано',{exact:true}).first()).toBeVisible()
    expect((await recipient.request.get('/api/admin/onboarding/drafts/'+draft.id)).status()).toBe(403)
    await manager.reload()
    await expect(manager.getByRole('region',{name:'Подключение заведений'})).toHaveCount(0)
  }finally{await recipient.close()}
})
